use openidea_plugin::{Error, NotificationLevel, Range, TextEdit, host};
use std::collections::HashMap;
use std::collections::hash_map::Entry;
use std::fmt::Write;

pub const DEFINITIONS: &str = "luals.definitions";
const HEADER: &str = "---@meta\n";
const NEEDS_EMPTY_FILE: &str = "Open an empty .lua file (for example .cfxlua/natives.lua) and run the command again: \
                                its content is replaced by the definitions.";
const STATE_BAG_CLASS: &str = "---@class StateBag\n";
const STATE_BAG_WITH_KEYS: &str = "---@class StateBag\n---@field [string] any\n";

#[derive(Default)]
pub struct LualsFeature;

impl Feature for LualsFeature {
    fn command(&self, cx: &CommandCx, id: &str, _arg: Option<&str>) -> Option<CommandResult> {
        (id == DEFINITIONS).then(|| write_definitions(cx))
    }
}

fn write_definitions(cx: &CommandCx) -> CommandResult {
    let editor = cx.inv.editor().ok_or(NEEDS_EMPTY_FILE)?;
    if !editor.path().to_ascii_lowercase().ends_with(".lua") {
        return Err(NEEDS_EMPTY_FILE.into());
    }
    let doc = editor.document()?;
    if !doc.text.trim().is_empty() && !doc.text.starts_with(HEADER) {
        return Err(Error::Invalid(format!(
            "This file is not empty and was not generated by this command. {NEEDS_EMPTY_FILE}"
        )));
    }
    let detected = cx.ws.map(|w| w.detected_games()).unwrap_or_default();
    let sets = sets_for(cx.settings, &detected);
    let (text, count) = definitions(cx.natives, &sets, &parts_for(cx.settings));
    let lines = LineIndex::new(&doc.text);
    let end = lines.position(&doc.text, doc.text.len());
    editor.apply_edits(doc.version, &[TextEdit { range: Range::new(Default::default(), end), text }])?;
    let names: Vec<&str> = sets.iter().map(|s| s.display_name()).collect();
    host::notify(
        NotificationLevel::Info,
        "CfxLua: lua-language-server definitions written",
        &format!(
            "{count} natives ({}) and the Cfx runtime API. Save the file: lua-language-server reads it as a definition \
             file (---@meta). Run the command again after a natives update.",
            names.join(", ")
        ),
    );
    Ok(None)
}

fn sets_for(settings: &Settings, detected: &[crate::project::Game]) -> Vec<NativeSet> {
    let mut sets = Vec::new();
    if settings.bool(keys::CLIENT_NATIVES, true) {
        sets.extend(project_games(settings, detected).into_iter().map(NativeSet::for_game));
    }
    if settings.bool(keys::SERVER_NATIVES, true) {
        sets.push(NativeSet::Server);
    }
    sets
}

fn parts_for(settings: &Settings) -> Vec<Part> {
    if !settings.bool(keys::RUNTIME_API, true) {
        return Vec::new();
    }
    let mut parts = vec![Part::Shared];
    if settings.bool(keys::CLIENT_NATIVES, true) {
        parts.push(Part::Client);
    }
    if settings.bool(keys::SERVER_NATIVES, true) {
        parts.push(Part::Server);
    }
    parts
}

/// The `---@meta` file and the number of natives in it.
pub fn definitions(natives: &Natives, sets: &[NativeSet], parts: &[Part]) -> (String, usize) {
    let mut groups: Vec<(NativeSet, Vec<&Native>)> = Vec::new();
    let mut index: HashMap<&str, usize> = HashMap::new();
    for &set in sets {
        for n in &natives.catalog(set).natives {
            match index.entry(n.lua_name.as_str()) {
                Entry::Occupied(e) => groups[*e.get()].1.push(n),
                Entry::Vacant(e) => {
                    e.insert(groups.len());
                    groups.push((set, vec![n]));
                }
            }
        }
    }
    let mut out = String::with_capacity(4 << 20);
    out.push_str(HEADER);
    out.push_str(
        "-- Generated by OpenIDEA-CfxLUA (CfxLua: Generate lua-language-server Definitions). Do not edit.\n\n",
    );
    let mut current = None;
    for (set, group) in &groups {
        if current != Some(*set) {
            current = Some(*set);
            let _ = writeln!(out, "-- {}\n", set.display_name());
        }
        write_native(&mut out, group);
    }
    for (part, file, text) in crate::runtime::stubs::FILES {
        if parts.contains(part) {
            let _ = writeln!(out, "-- {} ({file})\n", part.display_name());
            let body = strip_license_header(text).trim_start_matches(HEADER);
            out.push_str(&body.replace(STATE_BAG_CLASS, STATE_BAG_WITH_KEYS));
            out.push('\n');
        }
    }
    (out, groups.len())
}

fn strip_license_header(text: &str) -> &str {
    let mut rest = text;
    while let Some(line_end) = rest.find('\n') {
        let line = &rest[..line_end];
        if !(line.starts_with("--") && !line.starts_with("---")) {
            break;
        }
        rest = &rest[line_end + 1..];
    }
    rest.trim_start_matches(['\r', '\n'])
}

fn comment(out: &mut String, text: &str) {
    for line in text.trim().lines() {
        let line = line.trim_end();
        // A line starting with `@` would read as an annotation.
        if line.trim_start().starts_with('@') {
            let _ = writeln!(out, "--- \\{}", line.trim_start());
        } else {
            let _ = writeln!(out, "---{}{line}", if line.is_empty() { "" } else { " " });
        }
    }
}

/// Trailing booleans and untyped values may be omitted: the runtime passes them as `false` or `nil`.
fn optional_from(params: &[&Param]) -> usize {
    params
        .iter()
        .rposition(|p| !p.is_vararg() && !matches!(p.lua_type.as_str(), "boolean" | "any"))
        .map_or(0, |i| i + 1)
}

fn annotated_params(n: &Native) -> Vec<(String, &Param)> {
    let params: Vec<&Param> = n.lua_params().collect();
    let optional = optional_from(&params);
    params
        .into_iter()
        .enumerate()
        .map(|(i, p)| (if p.is_vararg() || i < optional { p.name.clone() } else { format!("{}?", p.name) }, p))
        .collect()
}

fn signature(n: &Native) -> String {
    let params: Vec<String> = annotated_params(n).iter().map(|(name, p)| format!("{name}: {}", p.lua_type)).collect();
    let returns: Vec<&str> = n.returns.iter().map(|r| r.lua_type.as_str()).collect();
    let returns = if returns.is_empty() { String::new() } else { format!(": {}", returns.join(", ")) };
    format!("fun({}){returns}", params.join(", "))
}

fn single_line(text: Option<&str>) -> String {
    text.map(|d| d.replace('\n', " ").trim().to_owned()).unwrap_or_default()
}

fn write_native(out: &mut String, group: &[&Native]) {
    let n = group[0];
    if !n.description.trim().is_empty() {
        comment(out, &n.description);
        out.push_str("---\n");
    }
    let mut details = format!("`{}` · {} · {} · {}", n.hash_display(), n.namespace, n.side_label(), n.game_label());
    if let Some(original) = &n.original_name {
        details = format!("`{original}` · {details}");
    }
    let _ = writeln!(out, "--- {details}");
    if !n.doc_url.is_empty() {
        let _ = writeln!(out, "---\n--- [Online documentation]({})", n.doc_url);
    }
    for (name, p) in annotated_params(n) {
        let _ = writeln!(out, "---@param {name} {} {}", p.lua_type, single_line(p.description.as_deref()));
    }
    for r in &n.returns {
        let _ = writeln!(out, "---@return {} {} {}", r.lua_type, r.name, single_line(r.description.as_deref()));
    }
    let mut signatures = vec![signature(n)];
    for other in &group[1..] {
        let sig = signature(other);
        if !signatures.contains(&sig) {
            let _ = writeln!(out, "---@overload {sig}");
            signatures.push(sig);
        }
    }
    if let Some(primary) = &n.alias_of {
        let _ = writeln!(out, "---@deprecated Use {primary}");
    }
    let args: Vec<&str> = n.lua_params().map(|p| p.name.as_str()).collect();
    let _ = writeln!(out, "function {}({}) end\n", n.lua_name, args.join(", "));
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::natives::Return;
    use crate::project::Side;
    use crate::testing::native;

    fn param(name: &str, lua_type: &str) -> Param {
        Param { name: name.into(), lua_type: lua_type.into(), native_type: lua_type.into(), ..Default::default() }
    }

    #[test]
    fn writes_annotated_functions_once() {
        let mut n = native(NativeSet::Gta5, "GetGroundZFor_3dCoord", Side::Client);
        n.description = "Finds the ground.\n@deprecated in docs".into();
        n.params = vec![
            param("x", "number"),
            Param { out_pointer: true, ..param("groundZ", "number") },
            param("ignoreWater", "boolean"),
        ];
        n.returns = vec![
            Return { name: "retval".into(), lua_type: "boolean".into(), native_type: "BOOL".into(), description: None },
            Return {
                name: "groundZ".into(),
                lua_type: "number".into(),
                native_type: "float*".into(),
                description: None,
            },
        ];
        let shared = native(NativeSet::Server, "GetGroundZFor_3dCoord", Side::Shared);
        let natives = Natives::from_natives(vec![n, shared, native(NativeSet::Server, "DropPlayer", Side::Server)]);
        let (text, count) = definitions(&natives, &[NativeSet::Gta5, NativeSet::Server], &[Part::Shared]);
        assert!(text.starts_with("---@meta\n"));
        assert_eq!(count, 2);
        assert_eq!(text.matches("function GetGroundZFor_3dCoord(x, ignoreWater) end").count(), 1);
        assert!(text.contains("---@param x number"));
        assert!(text.contains("---@param ignoreWater? boolean"));
        assert!(text.contains("---@return boolean retval"));
        assert!(text.contains("---@overload fun()\n"), "the server signature differs: {text}");
        assert!(text.contains("--- \\@deprecated in docs"), "{text}");
        assert!(text.contains("function DropPlayer() end"));
        assert!(text.contains("Citizen"), "the shared runtime API is appended");
        assert!(text.contains("---@class StateBag\n---@field [string] any\n"));
        assert!(!text.contains("Licensed under the Apache License"));
    }

    #[test]
    fn only_trailing_flags_are_optional() {
        let mut n = native(NativeSet::Gta5, "CreatePed", Side::Client);
        n.params = vec![
            param("model", "integer|string"),
            param("network", "boolean"),
            param("heading", "number"),
            param("p7", "any"),
        ];
        assert_eq!(signature(&n), "fun(model: integer|string, network: boolean, heading: number, p7?: any)");
        n.params.push(Param { name: "...".into(), ..param("...", "any") });
        assert_eq!(signature(&n), "fun(model: integer|string, network: boolean, heading: number, p7?: any, ...: any)");
    }

    #[test]
    #[ignore = "writes the definitions to $CFXLUA_DEFINITIONS for a lua-language-server --check run"]
    fn write_definitions_file() {
        let path = std::env::var("CFXLUA_DEFINITIONS").expect("CFXLUA_DEFINITIONS");
        let all = [Part::Shared, Part::Client, Part::Server];
        let (text, _) = definitions(&Natives::bundled(), &[NativeSet::Gta5, NativeSet::Rdr3, NativeSet::Server], &all);
        std::fs::write(path, text).expect("write");
    }

    #[test]
    fn real_catalogs_stay_reasonable() {
        let natives = Natives::bundled();
        let (text, count) =
            definitions(&natives, &[NativeSet::Gta5, NativeSet::Server], &[Part::Shared, Part::Client, Part::Server]);
        assert!(count > 9000, "{count}");
        assert!(text.len() < 16 << 20, "{} bytes", text.len());
        eprintln!("{count} natives, {} KiB", text.len() >> 10);
    }
}
