pub const DEFINITIONS: &str = "luals.definitions";
const HEADER: &str = "---@meta\n";
const GENERATED: &str = "-- Generated by OpenIDEA-CfxLUA";
const NATIVES_LINE: &str = "-- Natives:";
const RUNTIME_LINE: &str = "-- Runtime API:";
pub const LUARC: &str = ".luarc.json";
pub const LUARC_FILES: [&str; 2] = [LUARC, ".luarc.jsonc"];
const STORED: &str = "luals.definitions";
const REMEMBERED: usize = 16;
const NEEDS_EMPTY_FILE: &str = "Open an empty .lua file (for example .cfxlua/natives.lua) and run the command again: \
                                its content is replaced by the definitions.";
const STATE_BAG_CLASS: &str = "---@class StateBag\n";
const STATE_BAG_WITH_KEYS: &str = "---@class StateBag\n---@field [string] any\n";

#[derive(Default)]
pub struct LualsFeature;

impl Feature for LualsFeature {
    fn command(&self, cx: &CommandCx, id: &str, _arg: Option<&str>) -> Option<CommandResult> {
        (id == DEFINITIONS).then(|| write_definitions(cx))
    }
}

fn write_definitions(cx: &CommandCx) -> CommandResult {
    let editor = cx.inv.editor().ok_or(NEEDS_EMPTY_FILE)?;
    if !editor.path().to_ascii_lowercase().ends_with(".lua") {
        return Err(NEEDS_EMPTY_FILE.into());
    }
    let doc = editor.document()?;
    if !doc.text.trim().is_empty() && !doc.text.starts_with(HEADER) {
        return Err(Error::Invalid(format!(
            "This file is not empty and was not generated by this command. {NEEDS_EMPTY_FILE}"
        )));
    }
    let detected = cx.ws.map(|w| w.detected_games()).unwrap_or_default();
    let sets = sets_for(cx.settings, &detected);
    let (text, count) = definitions(cx.natives, &sets, &parts_for(cx.settings));
    let lines = LineIndex::new(&doc.text);
    let end = lines.position(&doc.text, doc.text.len());
    editor.apply_edits(doc.version, &[TextEdit { range: Range::new(Default::default(), end), text }])?;
    remember(&editor.path());
    let names: Vec<&str> = sets.iter().map(|s| s.display_name()).collect();
    let written = format!("{count} natives ({}) and the Cfx runtime API.", names.join(", "));
    match cx.ws.and_then(|ws| library_problem(ws, &editor.path())) {
        Some(problem) => host::notify(
            NotificationLevel::Warning,
            "CfxLua: definitions written, but lua-language-server will not keep them",
            &format!("{written} {problem}"),
        ),
        None => host::notify(
            NotificationLevel::Info,
            "CfxLua: lua-language-server definitions written",
            &format!(
                "{written} Save the file; you may then close it, lua-language-server loads it as a library. Run the \
                 command again after a natives update."
            ),
        ),
    }
    Ok(None)
}

/// Why lua-language-server would only see the definitions while their file is open.
fn library_problem(ws: &Workspace, path: &str) -> Option<String> {
    let path = slash(path);
    if !ws.contains(&path) {
        return None;
    }
    let file = ws.relative(&path);
    let projects = host::projects().ok()?;
    let config = LUARC_FILES.iter().find_map(|name| projects.iter().find_map(|p| p.read_file(&ws.absolute(name)).ok()));
    let Some(config) = config else {
        return Some(format!(
            "There is no {LUARC} at the root of the project: lua-language-server sees the natives only while this \
             file is open. Create one with New › lua-language-server config (.luarc.json)."
        ));
    };
    let library = library(&config)?;
    let dir = parent(file);
    (!lists(ws, &library, file)).then(|| {
        format!(
            "The {LUARC} at the root of the project does not list \"{dir}\" in workspace.library: lua-language-server \
             sees the natives only while this file is open."
        )
    })
}

fn luarc_text(ws: &Workspace) -> Option<&str> {
    LUARC_FILES.iter().find_map(|name| ws.text(&ws.absolute(name)))
}

/// The `workspace.library` entries of a `.luarc.json`, in every form lua-language-server reads; `None` when it does
/// not parse.
fn library(config: &str) -> Option<Vec<String>> {
    let json = strip_jsonc(&strip_jsonc(config.trim_start_matches('\u{feff}')));
    let config: serde_json::Value = serde_json::from_str(&json).ok()?;
    let entries = config
        .get("workspace.library")
        .or_else(|| config.get("Lua.workspace.library"))
        .or_else(|| config.get("workspace")?.get("library"))
        .or_else(|| config.get("Lua")?.get("workspace.library"))
        .or_else(|| config.get("Lua")?.get("workspace")?.get("library"));
    let entries = entries.and_then(|l| l.as_array()).map(Vec::as_slice).unwrap_or_default();
    Some(entries.iter().filter_map(|e| e.as_str()).map(slash).collect())
}

/// lua-language-server reads its configuration as JSON with comments and trailing commas. A comma before a comment
/// is only dropped by a second pass.
fn strip_jsonc(text: &str) -> String {
    let b = text.as_bytes();
    let mut out: Vec<u8> = Vec::with_capacity(b.len());
    let (mut i, mut in_string) = (0, false);
    while i < b.len() {
        let c = b[i];
        if in_string {
            out.push(c);
            if c == b'\\' && i + 1 < b.len() {
                out.push(b[i + 1]);
                i += 2;
                continue;
            }
            in_string = c != b'"';
            i += 1;
            continue;
        }
        match c {
            b'"' => {
                in_string = true;
                out.push(c);
                i += 1;
            }
            b'/' if b.get(i + 1) == Some(&b'/') => {
                while i < b.len() && b[i] != b'\n' {
                    i += 1;
                }
            }
            b'/' if b.get(i + 1) == Some(&b'*') => {
                i += 2;
                while i + 1 < b.len() && !(b[i] == b'*' && b[i + 1] == b'/') {
                    i += 1;
                }
                i = (i + 2).min(b.len());
            }
            b',' => {
                let next = b[i + 1..].iter().find(|c| !c.is_ascii_whitespace());
                if !matches!(next, Some(b']' | b'}')) {
                    out.push(c);
                }
                i += 1;
            }
            _ => {
                out.push(c);
                i += 1;
            }
        }
    }
    String::from_utf8(out).unwrap_or_default()
}

/// A library entry relative to the project root; `None` for a place outside it or a variable left unresolved.
fn relative_entry(ws: &Workspace, entry: &str) -> Option<String> {
    let entry = slash(entry);
    let entry = match entry.strip_prefix("${workspaceFolder}") {
        Some(rest) => rest.trim_start_matches('/').to_owned(),
        None => entry,
    };
    if entry.starts_with("${") || entry.starts_with('~') {
        return None;
    }
    let entry = entry.trim_start_matches("./").trim_end_matches('/');
    let entry = if entry == "." { "" } else { entry };
    let root = ws.root.as_str();
    if !root.is_empty()
        && let Some(head) = entry.get(..root.len())
        && head.eq_ignore_ascii_case(root)
    {
        let rest = &entry[root.len()..];
        return if rest.is_empty() { Some(String::new()) } else { rest.strip_prefix('/').map(str::to_owned) };
    }
    if entry.starts_with('/') || entry.contains(':') {
        return None;
    }
    Some(entry.to_owned())
}

/// lua-language-server loads `file` (relative to the root) as a library: it is listed, or lies in a listed folder,
/// at any depth.
fn lists(ws: &Workspace, library: &[String], file: &str) -> bool {
    library.iter().filter_map(|e| relative_entry(ws, e)).any(|e| {
        e.is_empty()
            || file.eq_ignore_ascii_case(&e)
            || (file.get(..e.len()).is_some_and(|head| head.eq_ignore_ascii_case(&e))
                && file.as_bytes().get(e.len()) == Some(&b'/'))
    })
}

fn remembered() -> Vec<String> {
    host::storage::get(STORED).ok().flatten().and_then(|s| serde_json::from_str(&s).ok()).unwrap_or_default()
}

fn remember(path: &str) {
    let path = slash(path);
    let mut paths = remembered();
    paths.retain(|p| *p != path);
    paths.insert(0, path);
    paths.truncate(REMEMBERED);
    if let Ok(json) = serde_json::to_string(&paths) {
        let _ = host::storage::set(STORED, &json);
    }
}

/// The definitions files to read by name, as the host does not list hidden folders: those the command wrote, and
/// `natives.lua` in each library folder.
pub fn candidates(ws: &Workspace) -> Vec<String> {
    let mut out: Vec<String> = remembered().into_iter().filter(|p| ws.contains(p)).collect();
    for entry in luarc_text(ws).and_then(library).unwrap_or_default() {
        let Some(rel) = relative_entry(ws, &entry) else { continue };
        let rel = match rel {
            r if r.is_empty() => continue,
            r if r.to_ascii_lowercase().ends_with(".lua") => r,
            r => format!("{r}/natives.lua"),
        };
        let path = ws.absolute(&rel);
        if !out.contains(&path) {
            out.push(path);
        }
    }
    out
}

/// The natives and runtime API parts of a definitions file this plugin wrote, read from its header.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Contents {
    pub sets: Vec<NativeSet>,
    pub parts: Vec<Part>,
}

impl Contents {
    pub fn of(text: &str) -> Option<Self> {
        let mut lines = text.lines();
        if lines.next() != Some(HEADER.trim_end()) || !lines.next()?.starts_with(GENERATED) {
            return None;
        }
        let mut contents = Self::default();
        for l in lines.take(2) {
            if let Some(ids) = l.strip_prefix(NATIVES_LINE) {
                contents.sets = ids.split_whitespace().filter_map(NativeSet::parse).collect();
            } else if let Some(labels) = l.strip_prefix(RUNTIME_LINE) {
                contents.parts =
                    labels.split_whitespace().filter_map(|s| Part::ALL.into_iter().find(|p| p.label() == s)).collect();
            }
        }
        Some(contents)
    }

    fn add(&mut self, other: &Self) {
        for &s in &other.sets {
            if !self.sets.contains(&s) {
                self.sets.push(s);
            }
        }
        for &p in &other.parts {
            if !self.parts.contains(&p) {
                self.parts.push(p);
            }
        }
    }
}

/// What lua-language-server loads of the definitions files this plugin wrote: those in a `workspace.library` folder.
/// It completes these natives and runtime API parts itself.
pub fn loaded<'a>(ws: &Workspace, files: impl Iterator<Item = (&'a String, &'a Contents)>) -> Contents {
    let mut out = Contents::default();
    let Some(library) = luarc_text(ws).and_then(library) else { return out };
    for (path, contents) in files {
        if lists(ws, &library, ws.relative(path)) {
            out.add(contents);
        }
    }
    out
}

fn sets_for(settings: &Settings, detected: &[crate::project::Game]) -> Vec<NativeSet> {
    let mut sets = Vec::new();
    if settings.bool(keys::CLIENT_NATIVES, true) {
        sets.extend(project_games(settings, detected).into_iter().map(NativeSet::for_game));
    }
    if settings.bool(keys::SERVER_NATIVES, true) {
        sets.push(NativeSet::Server);
    }
    sets
}

fn parts_for(settings: &Settings) -> Vec<Part> {
    if !settings.bool(keys::RUNTIME_API, true) {
        return Vec::new();
    }
    let mut parts = vec![Part::Shared];
    if settings.bool(keys::CLIENT_NATIVES, true) {
        parts.push(Part::Client);
    }
    if settings.bool(keys::SERVER_NATIVES, true) {
        parts.push(Part::Server);
    }
    parts
}

/// The `---@meta` file and the number of natives in it.
pub fn definitions(natives: &Natives, sets: &[NativeSet], parts: &[Part]) -> (String, usize) {
    let mut groups: Vec<(NativeSet, Vec<&Native>)> = Vec::new();
    let mut index: HashMap<&str, usize> = HashMap::new();
    for &set in sets {
        for n in &natives.catalog(set).natives {
            match index.entry(n.lua_name.as_str()) {
                Entry::Occupied(e) => groups[*e.get()].1.push(n),
                Entry::Vacant(e) => {
                    e.insert(groups.len());
                    groups.push((set, vec![n]));
                }
            }
        }
    }
    let mut out = String::with_capacity(4 << 20);
    out.push_str(HEADER);
    let _ = writeln!(out, "{GENERATED} (CfxLua: Generate lua-language-server Definitions). Do not edit.");
    let ids: Vec<&str> = sets.iter().map(|s| s.id()).collect();
    line(&mut out, &format!("{NATIVES_LINE} {}", ids.join(" ")));
    let labels: Vec<&str> = parts.iter().map(|p| p.label()).collect();
    line(&mut out, &format!("{RUNTIME_LINE} {}", labels.join(" ")));
    out.push('\n');
    let mut current = None;
    for (set, group) in &groups {
        if current != Some(*set) {
            current = Some(*set);
            let _ = writeln!(out, "-- {}\n", set.display_name());
        }
        write_native(&mut out, group);
    }
    for (part, file, text) in crate::runtime::stubs::FILES {
        if parts.contains(part) {
            let _ = writeln!(out, "-- {} ({file})\n", part.display_name());
            let body = strip_license_header(text).trim_start_matches(HEADER);
            out.push_str(&body.replace(STATE_BAG_CLASS, STATE_BAG_WITH_KEYS));
            out.push('\n');
        }
    }
    (out, groups.len())
}

fn strip_license_header(text: &str) -> &str {
    let mut rest = text;
    while let Some(line_end) = rest.find('\n') {
        let line = &rest[..line_end];
        if !(line.starts_with("--") && !line.starts_with("---")) {
            break;
        }
        rest = &rest[line_end + 1..];
    }
    rest.trim_start_matches(['\r', '\n'])
}

fn comment(out: &mut String, text: &str) {
    for line in text.trim().lines() {
        let line = line.trim_end();
        // A line starting with `@` would read as an annotation.
        if line.trim_start().starts_with('@') {
            let _ = writeln!(out, "--- \\{}", line.trim_start());
        } else {
            let _ = writeln!(out, "---{}{line}", if line.is_empty() { "" } else { " " });
        }
    }
}

/// Trailing booleans and untyped values may be omitted: the runtime passes them as `false` or `nil`.
fn optional_from(params: &[&Param]) -> usize {
    params
        .iter()
        .rposition(|p| !p.is_vararg() && !matches!(p.lua_type.as_str(), "boolean" | "any"))
        .map_or(0, |i| i + 1)
}

struct Slot<'a> {
    names: Vec<&'a str>,
    name: String,
    types: Vec<&'a str>,
    optional: bool,
    vararg: bool,
    description: Option<&'a str>,
}

impl<'a> Slot<'a> {
    fn new() -> Self {
        Self {
            names: Vec::new(),
            name: String::new(),
            types: Vec::new(),
            optional: false,
            vararg: false,
            description: None,
        }
    }

    fn add(&mut self, name: &'a str, lua_type: &'a str, description: Option<&'a str>) {
        if !self.names.contains(&name) {
            self.names.push(name);
        }
        let alternatives: Vec<&str> =
            if lua_type.contains(['(', '<', '{']) { vec![lua_type] } else { lua_type.split('|').collect() };
        for t in alternatives {
            if !self.types.contains(&t) {
                self.types.push(t);
            }
        }
        if self.description.is_none() {
            self.description = description.filter(|d| !d.trim().is_empty());
        }
    }

    fn annotated(&self) -> String {
        if self.optional && !self.vararg { format!("{}?", self.name) } else { self.name.clone() }
    }
}

/// Each slot takes the first of its games' names no earlier slot took: lua-language-server applies two `---@param`
/// of one name to the same argument.
fn name_slots(slots: &mut [Slot]) {
    let mut used: Vec<String> = Vec::new();
    for (i, slot) in slots.iter_mut().enumerate() {
        let free = slot.names.iter().find(|n| !used.iter().any(|u| u == *n));
        let mut name = free.map_or_else(|| format!("p{i}"), |n| (*n).to_owned());
        while used.contains(&name) {
            name.push('_');
        }
        used.push(name.clone());
        slot.name = name;
    }
}

/// One signature for a native of several games: lua-language-server lists every `---@overload` as a declaration
/// of its own. A parameter some of them lack is optional.
fn merged_params<'a>(group: &[&'a Native]) -> Vec<Slot<'a>> {
    let mut slots: Vec<Slot<'a>> = Vec::new();
    let mut shortest = usize::MAX;
    for &n in group {
        let params: Vec<&Param> = n.lua_params().collect();
        let optional = optional_from(&params);
        shortest = shortest.min(params.len());
        for (i, p) in params.into_iter().enumerate() {
            if i == slots.len() {
                slots.push(Slot::new());
            }
            let slot = &mut slots[i];
            slot.add(&p.name, &p.lua_type, p.description.as_deref());
            slot.optional |= i >= optional;
            slot.vararg |= p.is_vararg();
        }
    }
    for slot in slots.iter_mut().skip(shortest) {
        slot.optional = true;
    }
    name_slots(&mut slots);
    slots
}

fn merged_returns<'a>(group: &[&'a Native]) -> Vec<Slot<'a>> {
    let mut slots: Vec<Slot<'a>> = Vec::new();
    for &n in group {
        for (i, r) in n.returns.iter().enumerate() {
            if i == slots.len() {
                slots.push(Slot::new());
            }
            slots[i].add(&r.name, &r.lua_type, r.description.as_deref());
        }
    }
    name_slots(&mut slots);
    slots
}

fn single_line(text: Option<&str>) -> String {
    text.map(|d| d.replace('\n', " ").trim().to_owned()).unwrap_or_default()
}

/// lua-language-server checks every line ending with a space in an open file, in quadratic time.
fn line(out: &mut String, text: &str) {
    out.push_str(text.trim_end());
    out.push('\n');
}

fn write_native(out: &mut String, group: &[&Native]) {
    let n = group[0];
    if !n.description.trim().is_empty() {
        comment(out, &n.description);
        out.push_str("---\n");
    }
    let mut details = format!("`{}` · {} · {} · {}", n.hash_display(), n.namespace, n.side_label(), n.game_label());
    if let Some(original) = &n.original_name {
        details = format!("`{original}` · {details}");
    }
    line(out, &format!("--- {details}"));
    if !n.doc_url.is_empty() {
        let _ = writeln!(out, "---\n--- [Online documentation]({})", n.doc_url);
    }
    let params = merged_params(group);
    for p in &params {
        line(out, &format!("---@param {} {} {}", p.annotated(), p.types.join("|"), single_line(p.description)));
    }
    for r in merged_returns(group) {
        line(out, &format!("---@return {} {} {}", r.types.join("|"), r.name, single_line(r.description)));
    }
    // A native that is an alias in one game may be the primary name in another.
    if let Some(primary) = &n.alias_of
        && group.iter().all(|m| m.alias_of.is_some())
    {
        let _ = writeln!(out, "---@deprecated Use {primary}");
    }
    let args: Vec<&str> = params.iter().map(|p| p.name.as_str()).collect();
    let _ = writeln!(out, "function {}({}) end\n", n.lua_name, args.join(", "));
}

