    #[test]
    fn real_catalogs_stay_reasonable() {
        let natives = Natives::bundled();
        let (text, count) =
            definitions(&natives, &[NativeSet::Gta5, NativeSet::Server], &[Part::Shared, Part::Client, Part::Server]);
        assert!(count > 9000, "{count}");
        assert!(text.len() < 16 << 20, "{} bytes", text.len());
        assert_eq!(text.lines().filter(|l| l.ends_with([' ', '\t'])).count(), 0, "lines ending with a space");
        let all = [NativeSet::Gta5, NativeSet::Rdr3, NativeSet::Server];
        let (every_game, _) = definitions(&natives, &all, &[]);
        let repeated: Vec<&str> = every_game
            .lines()
            .filter(|l| l.starts_with("function "))
            .filter(|l| {
                let args: Vec<&str> = l[l.find('(').unwrap_or(0) + 1..l.rfind(')').unwrap_or(0)].split(", ").collect();
                args.iter().enumerate().any(|(i, a)| !a.is_empty() && args[..i].contains(a))
            })
            .collect();
        assert!(repeated.is_empty(), "{repeated:?}");
        eprintln!("{count} natives, {} KiB", text.len() >> 10);
    }
